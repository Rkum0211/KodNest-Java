public class StringMethod5 {
    public static void main(java.lang.String[] args) {
        java.lang.String s1 = "Rahul";
        java.lang.String s2 = "Ravi";
        java.lang.String s3 = s1 + s2;
        System.out.println(s3);
        java.lang.String t1 = new java.lang.String("Bhanu");
        java.lang.String t2 = new java.lang.String("Rishab");
        java.lang.String res = t1.concat(t2);
        System.out.println(res);
    }
}
